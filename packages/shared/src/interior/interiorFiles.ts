/**
 * Layout of the committed interior data: one JSON per space plus
 * `_library.json`, and a generated `index.ts` that statically imports them
 * (client and server bundles cannot glob a directory). Writers (Studio bridge,
 * scaffolder) keep `index.ts` in step with the space files.
 */
export const INTERIOR_DATA_RELATIVE_DIR = "packages/shared/src/data/interiors";
export const INTERIOR_LIBRARY_FILE_NAME = "_library.json";
export const INTERIOR_INDEX_FILE_NAME = "index.ts";

export function interiorSpaceFileName(spaceId: string): string {
  return `${spaceId}.json`;
}

/** Space ids in the order the index (and therefore every view) lists them. */
export function sortInteriorSpaceIds(spaceIds: readonly string[]): string[] {
  return [...new Set(spaceIds)].sort((left, right) => left < right ? -1 : left > right ? 1 : 0);
}

/** Source of `data/interiors/index.ts` for the given space ids. */
export function interiorIndexSource(spaceIds: readonly string[]): string {
  const ids = sortInteriorSpaceIds(spaceIds);
  return [
    "// Generated by the Studio bridge / dungeon scaffolder. Do not edit by hand.",
    `import library from "./${INTERIOR_LIBRARY_FILE_NAME}" with { type: "json" };`,
    ...ids.map((id, index) => `import space${index} from "./${interiorSpaceFileName(id)}" with { type: "json" };`),
    "",
    `export const INTERIOR_DATA = { library, spaces: [${ids.map((_, index) => `space${index}`).join(", ")}] };`,
    ""
  ].join("\n");
}
