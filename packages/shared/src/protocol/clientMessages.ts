const contextualClientMessageSchema = clientMessageDispatchSchema.superRefine(
  (message, context) => {
    if (message.type === "DASH") {
      if (!isDashDirectionUnit(message.dirX, message.dirY)) {
        context.addIssue({
          code: z.ZodIssueCode.custom,
          path: ["dirX"],
          message: "Dash direction must be a unit vector"
        });
      }
      return;
    }
    if (message.type === "SWING") {
      if (!isDashDirectionUnit(message.dirX, message.dirY)) {
        context.addIssue({
          code: z.ZodIssueCode.custom,
          path: ["dirX"],
          message: "Swing direction must be a unit vector"
        });
      }
      return;
    }
    if (
      message.type !== "PREPARE_WORLD_MAP_TRAVEL" &&
      message.type !== "SET_WORLD_MAP_DESTINATION_VISIBILITY"
    ) return;
    if (isWorldDestinationIdentityValid(message.destinationKind, message.destinationId)) return;
    context.addIssue({
      code: z.ZodIssueCode.custom,
      path: ["destinationId"],
      message: "Invalid UUID destination id"
    });
  }
);

// Keep the canonical fast type dispatcher visible to schema ownership tooling while
// parsing through the contextual kind/id validation above.
export const clientMessageSchema = Object.assign(contextualClientMessageSchema, {
  options: clientMessageDispatchSchema.options
}) as unknown as typeof clientMessageDispatchSchema;

export type ClientMessage = z.infer<typeof clientMessageSchema>;

export function parseClientMessage(raw: string): ClientMessage {
  return clientMessageSchema.parse(JSON.parse(raw));
}
