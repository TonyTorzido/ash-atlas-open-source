/**
 * Damage matrix v4 types for every mob archetype (docs/plans/class-roster-v2.md 6.5 and section 12).
 * Drafted from each MOB_MATCHUPS flavor name with the spec's family defaults, then hand-reviewed
 * (docs/plans/damage-matrix-v4-review.md lists every row with its source names and the review changes):
 *
 * - Armour: fur, hide, feathers -> leather; scales, chitin, mail -> mail; shell, stone, plate -> plate;
 *   soft bodies, skin, robes, rags -> cloth; skeletons and corporeal undead -> bone; ghosts, wights,
 *   wisps -> spirit; slimes, tar, ink, water elementals -> ooze; trees and plant creatures -> bark.
 * - Attack: claws, bites, blades -> slash; beaks, stings, horns, spears, knives, arrows -> pierce;
 *   slams, fists, clubs, kicks, tentacles -> blunt; ghosts, casters, breath, lightning -> arcane.
 *
 * Tier (owner, 2026-10-21) sets the mob's base hit: tuned so an equal-level hit at matrix multiplier 1.0
 * kills a 100 HP player in about 14 hits (low), 8 (medium) or 4 (strong), after the mob's damageMultiplier
 * (retuned from 10 / 5-6 / 2-3, owner 2026-10-21).
 * Drafted from the mob value pass labels: elite or boss spawn rarity, a damageMultiplier above 1, or a
 * miniboss -> strong; rare spawn or 9+ target hits ("Hunt") -> medium; the rest (Critter, Game) -> low.
 * Armour multipliers and the 5%-per-level rule still apply on top. Every archetype must be listed; a
 * missing key is a compile error.
 */
export const MOB_V4_TIERS = ["low", "medium", "strong"] as const;
export type MobV4Tier = (typeof MOB_V4_TIERS)[number];

/** Base hit per tier: 100 / 7 = ~14 hits, 100 / 12 = ~8 hits, 100 / 25 = 4 hits (3 with a x1.5 boss multiplier). */
export const MOB_V4_TIER_BASE_DAMAGE = Object.freeze({
  low: 7,
  medium: 12,
  strong: 25
} as const satisfies Readonly<Record<MobV4Tier, number>>);

export type MobV4Types = Readonly<{ damageType: DamageTypeV4; armourType: ArmourTypeV4; tier: MobV4Tier }>;

function v4(damageType: DamageTypeV4, armourType: ArmourTypeV4, tier: MobV4Tier): MobV4Types {
  return Object.freeze({ damageType, armourType, tier });
}

