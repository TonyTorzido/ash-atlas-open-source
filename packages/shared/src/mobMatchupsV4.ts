export type MobV4Profile = Readonly<{
  damageType: DamageTypeV4;
  armourType: ArmourTypeV4;
  tier: MobV4Tier;
  baseDamage: number;
  damageMultiplier: number;
}>;

export function mobV4Profile(archetype: MobArchetypeKey): MobV4Profile {
  const types = MOB_V4_TYPES[archetype];
  const matchup = MOB_MATCHUPS[archetype];
  return {
    damageType: types.damageType,
    armourType: types.armourType,
    tier: types.tier,
    baseDamage: MOB_V4_TIER_BASE_DAMAGE[types.tier],
    damageMultiplier: matchup.damageMultiplier
  };
}
