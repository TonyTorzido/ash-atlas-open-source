/** The archetype whose own gimmick (ink drift, rift, burst, shell) this mob uses: a dungeon variant's base, else itself. */
export function mobGimmickArchetype<Key extends string>(value: Key): Key | MobArchetypeKey {
  return Object.prototype.hasOwnProperty.call(DUNGEON_MOB_VARIANT_BASES, value)
    ? DUNGEON_MOB_VARIANT_BASES[value as unknown as DungeonMobVariantArchetype]
    : value;
}
export type FantasyMobArchetype = keyof typeof FANTASY_MOB_TEMPLATES;
export type FantasyMobTemplate = (typeof FANTASY_MOB_TEMPLATES)[FantasyMobArchetype];
export const FANTASY_MOB_ARCHETYPES = Object.freeze(
  Object.keys(FANTASY_MOB_TEMPLATES) as FantasyMobArchetype[]
);

export function isFantasyMobArchetype(value: string | null | undefined): value is FantasyMobArchetype {
  return value != null && Object.prototype.hasOwnProperty.call(FANTASY_MOB_TEMPLATES, value);
}

/** A fantasy or animal template mob's template, or null for any other mob. */
export function mobTemplateOf(value: string): MobTemplateKey | null {
  if (isFantasyMobArchetype(value)) return FANTASY_MOB_TEMPLATES[value];
  if (isAnimalMobArchetype(value)) return ANIMAL_MOB_TEMPLATES[value];
  return null;
}

/** Template mobs whose template is a mob (not a world template) behave like it. */
type MobBehaviorTemplate = Exclude<
  FantasyMobTemplate | (typeof ANIMAL_MOB_TEMPLATES)[AnimalMobArchetype],
  WorldMobTemplateKey
>;

/**
 * The archetype whose behaviour this mob uses: a biome variant maps to its
 * family base (frost_wolf -> wolf), a template mob to its template (yeti ->
 * bear); a mob on a world template, and anything else, maps to itself.
 */
export function mobBehaviorArchetype<Key extends string>(
  value: Key
): Key | MobBiomeVariantFamilyBase | MobBehaviorTemplate {
  const template = mobTemplateOf(value);
  const behaviour = template === null || isWorldMobTemplateKey(template)
    ? value
    : template as MobBehaviorTemplate;
  return MOB_FAMILY_BASE_BY_ARCHETYPE.get(behaviour) ?? behaviour;
}

/** True when the archetype is the base or a biome variant of that family. */
export function isMobFamilyArchetype(
  value: string | null | undefined,
  base: MobBiomeVariantFamilyBase
): boolean {
  return value != null && MOB_FAMILY_BASE_BY_ARCHETYPE.get(value) === base;
}

export function isWolfFamilyArchetype(value: string | null | undefined): value is WolfFamilyArchetype {
  return isMobFamilyArchetype(value, "wolf");
}

