function dropItem(
  itemId: MobDropItemId,
  displayName: string,
  rarity: ItemRarity,
  group: InventoryItemGroupId | null,
  unitWeightGrams: number,
  maxStack: number
): MobDropItemDefinition {
  return {
    itemId,
    displayName,
    rarity,
    group,
    unitWeightGrams,
    maxStack,
    assetPath: `apps/client/src/assets/items/${itemId.replaceAll("_", "-")}.png`
  };
}

export function isMobDropItemId(itemId: string): itemId is MobDropItemId {
  return Object.hasOwn(MOB_DROP_ITEMS, itemId);
}
