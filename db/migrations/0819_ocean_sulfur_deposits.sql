-- Add Sulfur as a normal fungible resource and an independent, immutable
-- ocean-only permanent mine family. Sulfur never enters the retained
-- Population V2 stone/coal/iron classifier or remaps those identities.

INSERT INTO item_definitions (
  item_id, display_name, category, stackable, max_stack,
  droppable, manor_storable, market_tradable, market_fungible,
  market_identity, supported_variants
)
VALUES (
  'sulfur', 'Sulfur', 'resource', true, 250,
  true, true, true, true, 'sulfur', ARRAY['default']::text[]
)
ON CONFLICT (item_id) DO UPDATE SET
  display_name=EXCLUDED.display_name,
  category=EXCLUDED.category,
  stackable=EXCLUDED.stackable,
  max_stack=EXCLUDED.max_stack,
  droppable=EXCLUDED.droppable,
  manor_storable=EXCLUDED.manor_storable,
  market_tradable=EXCLUDED.market_tradable,
  market_fungible=EXCLUDED.market_fungible,
  market_identity=EXCLUDED.market_identity,
  supported_variants=EXCLUDED.supported_variants,
  updated_at=now();

-- The base slot table remains the durable state FK target, but Sulfur slots
-- are generated by their own ocean placement family and have no generation
-- lease. Existing slot identities and the old mine classifier are untouched.
ALTER TABLE population_spawn_slots_v2
  DROP CONSTRAINT IF EXISTS population_spawn_slots_v2_lifecycle_shape,
  DROP CONSTRAINT IF EXISTS population_spawn_slots_v2_entity_shape_check,
  ADD CONSTRAINT population_spawn_slots_v2_lifecycle_shape CHECK (
    (
      entity_kind IN ('stone', 'coal', 'iron', 'sulfur')
      AND generation_id IS NULL
    )
    OR
    (
      entity_kind NOT IN ('stone', 'coal', 'iron', 'sulfur')
      AND generation_id IS NOT NULL
    )
  ),
  ADD CONSTRAINT population_spawn_slots_v2_entity_shape_check CHECK (
    (
      archetype IN (
        'tree', 'flax', 'stone_mine', 'coal_mine', 'iron_mine',
        'sulfur_mine'
      )
      AND encounter_id IS NULL AND pack_id IS NULL
      AND pack_member_index IS NULL
    )
    OR
    (
      archetype NOT IN (
        'tree', 'flax', 'stone_mine', 'coal_mine', 'iron_mine',
        'sulfur_mine'
      )
      AND encounter_id IS NOT NULL
      AND (
        (pack_id IS NULL AND pack_member_index IS NULL)
        OR (pack_id IS NOT NULL AND pack_member_index IS NOT NULL)
      )
    )
  );

CREATE TABLE IF NOT EXISTS population_ocean_sulfur_authority_v1 (
  entity_id uuid PRIMARY KEY
    REFERENCES population_spawn_slots_v2(entity_id) ON DELETE RESTRICT,
  slot_id uuid NOT NULL UNIQUE,
  candidate_id text NOT NULL CHECK (candidate_id <> ''),
  owner_zone_id text NOT NULL CHECK (owner_zone_id <> ''),
  entity_kind text NOT NULL CHECK (entity_kind = 'sulfur'),
  archetype text NOT NULL CHECK (archetype = 'sulfur_mine'),
  placement_version text NOT NULL
    CHECK (placement_version = 'ocean-sulfur-placement-v1'),
  yield_item_id text NOT NULL
    REFERENCES item_definitions(item_id) ON DELETE RESTRICT
    CHECK (yield_item_id = 'sulfur'),
  yield_quantity integer NOT NULL CHECK (yield_quantity = 1),
  regeneration_interval interval NOT NULL
    CHECK (regeneration_interval = interval '5 hours 50 minutes'),
  timer_profession_id text NOT NULL CHECK (timer_profession_id = 'miner'),
  timer_visibility_rank integer NOT NULL CHECK (timer_visibility_rank = 2),
  world_environment_identity_key text NOT NULL
    CHECK (world_environment_identity_key ~ '^[a-f0-9]{64}$'),
  latitude double precision NOT NULL CHECK (latitude BETWEEN -90 AND 90),
  longitude double precision NOT NULL CHECK (longitude BETWEEN -180 AND 180),
  anchor_latitude double precision NOT NULL
    CHECK (anchor_latitude BETWEEN -90 AND 90),
  anchor_longitude double precision NOT NULL
    CHECK (anchor_longitude BETWEEN -180 AND 180),
  environment_snapshot jsonb NOT NULL
    CHECK (jsonb_typeof(environment_snapshot) = 'object'),
  suppression_class text NOT NULL CHECK (suppression_class = 'none'),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE INDEX IF NOT EXISTS population_ocean_sulfur_authority_zone_idx
  ON population_ocean_sulfur_authority_v1 (owner_zone_id, entity_id);

CREATE TABLE IF NOT EXISTS population_plan_ocean_sulfur_v1 (
  plan_id uuid NOT NULL
    REFERENCES population_zones_v2(plan_id) ON DELETE RESTRICT,
  entity_id uuid NOT NULL
    REFERENCES population_ocean_sulfur_authority_v1(entity_id)
    ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  PRIMARY KEY (plan_id, entity_id)
);

CREATE OR REPLACE FUNCTION validate_population_ocean_sulfur_insert_v1()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE stored record;
BEGIN
  SELECT slot.*, plan.zone_id, plan.world_environment_identity_key
  INTO stored
  FROM population_spawn_slots_v2 AS slot
  JOIN population_zones_v2 AS plan ON plan.plan_id=slot.plan_id
  WHERE slot.entity_id=NEW.entity_id;
  IF NOT FOUND
    OR stored.generation_id IS NOT NULL
    OR stored.entity_kind IS DISTINCT FROM 'sulfur'
    OR stored.archetype IS DISTINCT FROM 'sulfur_mine'
    OR stored.slot_id IS DISTINCT FROM NEW.slot_id
    OR stored.candidate_id IS DISTINCT FROM NEW.candidate_id
    OR stored.zone_id IS DISTINCT FROM NEW.owner_zone_id
    OR stored.world_environment_identity_key
      IS DISTINCT FROM NEW.world_environment_identity_key
    OR stored.latitude IS DISTINCT FROM NEW.latitude
    OR stored.longitude IS DISTINCT FROM NEW.longitude
    OR stored.anchor_latitude IS DISTINCT FROM NEW.anchor_latitude
    OR stored.anchor_longitude IS DISTINCT FROM NEW.anchor_longitude
    OR stored.environment_snapshot IS DISTINCT FROM NEW.environment_snapshot
    OR stored.suppression_class IS DISTINCT FROM NEW.suppression_class
  THEN
    RAISE EXCEPTION
      'population ocean sulfur authority does not match its physical slot'
      USING ERRCODE='23514',
            CONSTRAINT='population_ocean_sulfur_authority_v1_slot_mismatch';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS population_ocean_sulfur_authority_v1_validate_insert
  ON population_ocean_sulfur_authority_v1;
CREATE TRIGGER population_ocean_sulfur_authority_v1_validate_insert
BEFORE INSERT ON population_ocean_sulfur_authority_v1
FOR EACH ROW EXECUTE FUNCTION validate_population_ocean_sulfur_insert_v1();

CREATE OR REPLACE FUNCTION validate_population_plan_ocean_sulfur_insert_v1()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE plan_zone_id text; sulfur_zone_id text;
BEGIN
  SELECT zone_id INTO STRICT plan_zone_id
  FROM population_zones_v2 WHERE plan_id=NEW.plan_id;
  SELECT owner_zone_id INTO STRICT sulfur_zone_id
  FROM population_ocean_sulfur_authority_v1 WHERE entity_id=NEW.entity_id;
  IF plan_zone_id IS DISTINCT FROM sulfur_zone_id THEN
    RAISE EXCEPTION
      'population plan cannot adopt ocean sulfur from another physical zone'
      USING ERRCODE='23514',
            CONSTRAINT='population_plan_ocean_sulfur_v1_owner_mismatch';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS population_plan_ocean_sulfur_v1_validate_insert
  ON population_plan_ocean_sulfur_v1;
CREATE TRIGGER population_plan_ocean_sulfur_v1_validate_insert
BEFORE INSERT ON population_plan_ocean_sulfur_v1
FOR EACH ROW EXECUTE FUNCTION validate_population_plan_ocean_sulfur_insert_v1();

CREATE OR REPLACE FUNCTION reject_population_ocean_sulfur_change_v1()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'population ocean sulfur authority is immutable'
    USING ERRCODE='23514',
          CONSTRAINT='population_ocean_sulfur_authority_v1_immutable';
END;
$$;

