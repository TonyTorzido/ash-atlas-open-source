type FamilyMap = typeof CLIENT_MESSAGE_FAMILIES;
type MessageTypeForFamily<Family extends RealtimeMessageFamily> = {
  [Type in keyof FamilyMap]: FamilyMap[Type] extends Family ? Type : never;
}[keyof FamilyMap];

export type MessageForFamily<Family extends RealtimeMessageFamily> = Extract<
  ClientMessage,
  { type: MessageTypeForFamily<Family> }
>;

export type RealtimeFamilyHandler<Family extends RealtimeMessageFamily> = (
  message: MessageForFamily<Family>
) => void | Promise<void>;

export type RealtimeMessageDispatch = (message: ClientMessage) => void | Promise<void>;

export class RealtimeMessageRouter {
  private readonly handlers = new Map<
    RealtimeMessageFamily,
    RealtimeMessageDispatch
  >();

  register<Family extends RealtimeMessageFamily>(
    family: Family,
    handler: RealtimeFamilyHandler<Family>
  ): void {
    if (this.handlers.has(family)) {
      throw new Error(`Realtime message family '${family}' was registered more than once`);
    }
    this.handlers.set(family, handler as RealtimeMessageDispatch);
  }

  assertComplete(): void {
    const expected = new Set(Object.values(CLIENT_MESSAGE_FAMILIES));
    const missing = [...expected].filter((family) => !this.handlers.has(family));
    if (missing.length > 0) {
      throw new Error(`Realtime message families are missing handlers: ${missing.join(", ")}`);
    }
  }

  async dispatch(message: ClientMessage): Promise<void> {
    const family = CLIENT_MESSAGE_FAMILIES[message.type];
    const handler = this.handlers.get(family);
    if (!handler) throw new Error(`Realtime message family '${family}' has no handler`);
    await handler(message);
  }
}
