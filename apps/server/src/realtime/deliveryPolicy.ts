export function deliveryClassFor(
  message: ServerMessage,
  override?: OutboundSendMode
): DeliveryClass {
  if (
    message.type === "POPULATION_ZONE_DELTA" &&
    (message.terminal || message.preparationResult !== "pending")
  ) {
    return "terminal-population";
  }
  if (override === "replaceable") {
    return message.type.startsWith("COMBAT_")
      ? "replaceable-combat"
      : message.type.startsWith("POPULATION_")
        ? "replaceable-population"
        : "replaceable-world";
  }
  if (override === "recoverable-social" || override === "transient-social") {
    return override;
  }
  if (override === "critical") return "critical";
  return SERVER_MESSAGE_DELIVERY_POLICY[message.type];
}

export function sendModeForDeliveryClass(deliveryClass: DeliveryClass): OutboundSendMode {
  switch (deliveryClass) {
    case "replaceable-world":
    case "replaceable-combat":
    case "replaceable-population":
      return "replaceable";
    case "recoverable-social":
    case "transient-social":
      return deliveryClass;
    case "critical":
    case "terminal-population":
      return "critical";
  }
}
