function catalogQueryable(rows: unknown[]) {
  return { query: async (sql: string) => ({
    rows: sql.includes("inventory_carry_rules")
      ? [{default_base_capacity_grams:String(DEFAULT_PLAYER_CARRY_CAPACITY_GRAMS),backpack_unit_weight_grams:BACKPACK_WEIGHT_GRAMS}]
      : sql.includes("backpack_level_definitions")
      ? BACKPACK_LEVELS.map(level => ({level:level.level,
          capacity_bonus_grams:String(level.capacityBonusGrams),
          leather_cost:String(level.upgradeCost.leather),gold_cost:String(level.upgradeCost.gold),effects:level.effects}))
      : rows
  }) };
}
