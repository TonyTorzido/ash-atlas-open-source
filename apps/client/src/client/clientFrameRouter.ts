type TerminalServerMessage = Extract<
  ServerMessage,
  { type: "SESSION_REPLACED" | "AUTH_SESSION_INVALID" }
>;

type FeatureServerMessage = Exclude<ServerMessage, TerminalServerMessage>;

export type ClientFrameHandler = (message: FeatureServerMessage) => void;

export type ClientFrameHandlers = Record<ClientFrameFamily, ClientFrameHandler> & {
  terminal(message: TerminalServerMessage): void;
};

export type ClientFrameObserver = (
  message: FeatureServerMessage,
  family: ClientFrameFamily
) => void;

export function routeClientServerMessage(
  message: ServerMessage,
  handlers: ClientFrameHandlers,
  observers: readonly ClientFrameObserver[] = []
): void {
  if (message.type === "SESSION_REPLACED" || message.type === "AUTH_SESSION_INVALID") {
    handlers.terminal(message);
    return;
  }
  const family = CLIENT_SERVER_MESSAGE_OWNERSHIP[message.type];
  handlers[family](message);
  for (const observer of observers) observer(message, family);
}
