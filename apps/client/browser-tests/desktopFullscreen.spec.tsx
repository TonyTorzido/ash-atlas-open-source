import { expect, test } from "@playwright/experimental-ct-react";
import { DesktopFullscreenStory, AuthContrastStory, DesktopAtlasChatStory } from "./DesktopFullscreenStory.js";
import { FloatingMessagesStory } from "./MessagesNavigationStory.js";
import { MenuAppearanceStory } from "./PhoneHudLayoutStory.js";

for (const size of [{ width: 1280, height: 720 }, { width: 1440, height: 900 }]) {
  for (const theme of ["light", "dark"]) test(`full desktop ${size.width} ${theme}`, async ({ page, mount }, info) => {
    await page.setViewportSize(size);
    await page.evaluate((value) => { document.documentElement.dataset.menuTheme = value; }, theme);
    await mount(<DesktopFullscreenStory />);
    await expect(page.getByTestId("effective-viewport")).toHaveText(`${size.width}x${size.height}`);
    const stage = await page.getByTestId("mobile-app-stage").boundingBox();
    expect(stage).toEqual({ x: 0, y: 0, ...size });
    await expect(page.getByRole("button", { name: "Open Game Menu", exact: true })).toHaveCount(0);
    await expect(page.getByRole("button", { name: "Open Loadout for LoadoutQA", exact: true })).toBeVisible();
    const commands = page.getByRole("navigation", { name: "Game commands" });
    await expect(commands.getByRole("button")).toHaveCount(11);
    await commands.getByRole("button", { name: "Open Workshop menu" }).click();
    await expect(page.getByRole("button", { name: "Crafting", exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Cancel", exact: true }).click();
    const preview = page.getByRole("combobox", { name: "Preview presentation" });
    await preview.evaluate((element) => { element.style.opacity = "0"; });
    await page.screenshot({ path: info.outputPath("desktop.png") });
    await preview.selectOption("touch");
    await expect(page.getByRole("button", { name: "Open Game Menu", exact: true })).toBeVisible();
    expect((await page.getByTestId("mobile-app-stage").boundingBox())!.width).toBeLessThan(size.width);
    await page.screenshot({ path: info.outputPath("forced-touch.png") });
    await preview.selectOption("desktop");
    expect(await page.getByTestId("mobile-app-stage").boundingBox()).toEqual({ x: 0, y: 0, ...size });
    await expect(page.getByRole("button", { name: "Open Game Menu", exact: true })).toHaveCount(0);
  });
}

for (const kind of ["public", "direct"]) test(`desktop ${kind} chat drag resize keyboard clamp and session bounds`, async ({ page, mount }, info) => {
  await page.setViewportSize({ width: 1280, height: 720 });
  await page.evaluate(() => { document.documentElement.dataset.uiProfile = "phone"; document.documentElement.dataset.presentation = "desktop"; });
  const view = await mount(kind === "public" ? <DesktopAtlasChatStory /> : <FloatingMessagesStory />);
  if (kind === "public") await page.getByRole("button", { name: "Open General chat" }).click();
  const window = page.locator(".desktop-chat-window");
  const handle = page.getByRole("button", { name: kind === "public" ? "Move Atlas Chats window" : "Move Messages window" });
  const initial = (await window.boundingBox())!;
  const grip = (await handle.boundingBox())!;
  await page.mouse.move(grip.x + 15, grip.y + 15); await page.mouse.down();
  await page.mouse.move(grip.x + 115, grip.y + 45); await page.mouse.up();
  expect((await window.boundingBox())!.x).toBeGreaterThan(initial.x);
  await handle.focus(); await page.keyboard.press("ArrowRight");
  const moved = (await window.boundingBox())!;
  const resize = page.getByRole("button", { name: "Resize chat window" });
  const corner = (await resize.boundingBox())!;
  await page.mouse.move(corner.x + 10, corner.y + 10); await page.mouse.down();
  await page.mouse.move(corner.x + 90, corner.y - 100); await page.mouse.up();
  const resized = (await window.boundingBox())!;
  expect(resized.width).toBeGreaterThan(moved.width);
  expect(resized.height).toBeLessThan(moved.height);
  await resize.focus(); await page.keyboard.press("ArrowRight");
  await page.screenshot({ path: info.outputPath("chat-resized.png") });
  const saved = (await window.boundingBox())!;
  await view.unmount();
  await mount(kind === "public" ? <DesktopAtlasChatStory /> : <FloatingMessagesStory />);
  if (kind === "public") await page.getByRole("button", { name: "Open General chat" }).click();
  expect((await window.boundingBox())!.width).toBeCloseTo(saved.width);
  await page.setViewportSize({ width: 1100, height: 600 });
  await expect.poll(async () => { const rect = (await window.boundingBox())!; return rect.x + rect.width; }).toBeLessThanOrEqual(1100);
  const clamped = (await window.boundingBox())!;
  expect(clamped.x).toBeGreaterThanOrEqual(0); expect(clamped.y).toBeGreaterThanOrEqual(0);
  expect(clamped.x + clamped.width).toBeLessThanOrEqual(1100);
  expect(clamped.y + clamped.height).toBeLessThanOrEqual(600);
  await resize.focus();
  for (let index = 0; index < 20; index += 1) await page.keyboard.press("Shift+ArrowLeft");
  for (let index = 0; index < 20; index += 1) await page.keyboard.press("Shift+ArrowUp");
  await page.screenshot({ path: info.outputPath("chat-minimum.png") });
  expect((await window.boundingBox())!.width).toBe(420);
  expect((await window.boundingBox())!.height).toBe(300);
  expect(await window.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true);
  await page.reload();
  await mount(kind === "public" ? <DesktopAtlasChatStory /> : <FloatingMessagesStory />);
  if (kind === "public") await page.getByRole("button", { name: "Open General chat" }).click();
  expect((await window.boundingBox())!.width).toBe(kind === "public" ? 540 : 680);
});

for (const theme of ["light", "dark"]) test(`readable auth and Settings ${theme}`, async ({ page, mount }, info) => {
  await page.setViewportSize({ width: 735, height: 813 });
  await page.evaluate((value) => { document.documentElement.dataset.menuTheme = value; }, theme);
  const auth = await mount(<AuthContrastStory />);
  const expected = theme === "light" ? "rgb(55, 41, 31)" : "rgb(238, 227, 202)";
  await expect(page.locator(".auth-card h1")).toHaveCSS("color", expected);
  await page.screenshot({ path: info.outputPath("auth.png") });
  await auth.unmount();
  await page.setViewportSize({ width: 390, height: 844 });
  await mount(<MenuAppearanceStory />);
  await page.getByRole("tab", { name: "Appearance", exact: true }).click();
  await page.getByRole("combobox", { name: "Menu theme" }).selectOption(theme);
  await page.getByRole("tab", { name: "Support", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Help & Support" })).toHaveCSS("color", expected);
  await page.screenshot({ path: info.outputPath("help.png") });
  await page.getByRole("tab", { name: "About", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Map & Data Credits" })).toHaveCSS("color", expected);
  await page.screenshot({ path: info.outputPath("credits.png") });
  await page.getByRole("tab", { name: "Legal", exact: true }).click();
  await expect(page.getByRole("link", { name: "Privacy Policy" })).toHaveCSS("color", expected);
  await page.screenshot({ path: info.outputPath("legal.png") });
});
