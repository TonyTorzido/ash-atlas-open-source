import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// Regenerates apps/server/src/auth/trust/zoneCountries.ts from the IANA tz database
// (zone1970.tab plus zone.tab, so single-country link names resolve too).
//
//   node tools/trust/build-zone-countries.mjs <tzdata-dir>   (default /usr/share/zoneinfo)
//
// A zone lists every country that shares it; the anti-spoof country check accepts any of them.
const directory = process.argv[2] ?? "/usr/share/zoneinfo";
const output = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../../apps/server/src/auth/trust/zoneCountries.ts"
);

const zones = new Map();
for (const file of ["zone1970.tab", "zone.tab"]) {
  const text = await readFile(resolve(directory, file), "utf8");
  for (const line of text.split("\n")) {
    if (!line || line.startsWith("#")) continue;
    const [countries, , zone] = line.split("\t");
    if (!countries || !zone) continue;
    const set = zones.get(zone) ?? new Set();
    for (const country of countries.split(",")) set.add(country.trim().toUpperCase());
    zones.set(zone, set);
  }
}
const version = (await readFile(resolve(directory, "tzdata.zi"), "utf8").catch(() => "")).match(/^# version (\S+)/u)?.[1] ?? "unknown";
const rows = [...zones.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([zone, countries]) => `  ${JSON.stringify(zone)}: ${JSON.stringify([...countries].sort().join(" "))}`);
const source = `// Generated by tools/trust/build-zone-countries.mjs from IANA tzdata ${version}
// (zone1970.tab + zone.tab). Do not edit by hand.
// Zone -> ISO 3166-1 alpha-2 countries sharing it (space separated).
export const ZONE_COUNTRIES: Readonly<Record<string, string>> = {
${rows.join(",\n")}
};
`;
await writeFile(output, source);
process.stdout.write(`Wrote ${zones.size} zones (tzdata ${version}) to ${output}\n`);
